using Microsoft.CodeAnalysis.CSharp;

namespace DynaSharp.UnitTests.Generators;

/// <summary>The driver helper and the snapshot flow end to end, with a generator whose output is known.</summary>
public sealed class GeneratorRunTests
{
    [Test]
    public void Run_GeneratedFile_MatchesTheVerifiedSnapshot()
    {
        // Arrange
        var generator = new FixedTextGenerator("Hello.g.cs", TestSources.Greeting);

        // Act
        var output = GeneratorRun.Run(string.Empty, generator, LanguageVersion.Latest);

        // Assert
        SnapshotComparer.Verify("Hello.g", output.Result.Results[0].GeneratedSources.Single().SourceText.ToString());
    }

    [Test]
    [Arguments(LanguageVersion.CSharp11)]
    [Arguments(LanguageVersion.Latest)]
    public async Task Run_WellFormedGeneratedFile_HasNoWarningsAtEachLanguageVersion(LanguageVersion language)
    {
        // Arrange
        var generator = new FixedTextGenerator("Hello.g.cs", TestSources.Greeting);

        // Act
        var output = GeneratorRun.Run(string.Empty, generator, language);

        // Assert
        await Assert.That(output.Problems).IsEmpty();
    }

    [Test]
    [Arguments(LanguageVersion.CSharp11)]
    [Arguments(LanguageVersion.Latest)]
    public async Task Run_PublicMemberWithoutDocs_ReportsTheWarningInTheGeneratedFile(LanguageVersion language)
    {
        // Arrange
        var generator = new FixedTextGenerator("NoDocs.g.cs", "// <auto-generated/>\npublic class NoDocs { }\n");

        // Act
        var output = GeneratorRun.Run(string.Empty, generator, language);

        // Assert
        await Assert.That(output.Problems.Single()).Contains("warning CS1591");
    }

    [Test]
    public async Task Run_GeneratedFileThatDoesNotCompile_ReportsTheError()
    {
        // Arrange
        var generator = new FixedTextGenerator("Broken.g.cs", "// <auto-generated/>\ninternal class Broken : Missing { }\n");

        // Act
        var output = GeneratorRun.Run(string.Empty, generator, LanguageVersion.Latest);

        // Assert
        await Assert.That(output.Problems.Single()).Contains("error CS0246");
    }

    [Test]
    public async Task Run_WarningInTheInputSource_IsNotCountedAgainstTheGenerator()
    {
        // Arrange
        var generator = new FixedTextGenerator("Hello.g.cs", TestSources.Greeting);

        // Act
        var output = GeneratorRun.Run("public class Undocumented { }", generator, LanguageVersion.Latest);

        // Assert
        await Assert.That(output.Problems).IsEmpty();
    }

    [Test]
    public async Task Run_MoreSources_SeeTheGeneratedTextAndAreCompiled()
    {
        // Arrange
        var generator = new FixedTextGenerator("Hello.g.cs", TestSources.Greeting);

        // Act
        var output = GeneratorRun.Run(string.Empty, generator, LanguageVersion.Latest, generated => [$"internal class Broken{generated.Count()} : Missing {{ }}"]);

        // Assert
        await Assert.That(output.Problems.Single()).Contains("error CS0246");
    }
}
