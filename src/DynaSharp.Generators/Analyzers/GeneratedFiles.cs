using Microsoft.CodeAnalysis;

namespace DynaSharp.Generators;

/// <summary>Which files a code fix leaves alone: a file that a tool writes loses the edit when the tool runs again. The same tests as the compiler's for generated code, by name and by header.</summary>
internal static class GeneratedFiles
{
    private static readonly string[] Suffixes = [".g.cs", ".g.i.cs", ".designer.cs", ".generated.cs"];

    public static bool IsGenerated(SyntaxTree tree, CancellationToken token) =>
        Suffixes.Any(suffix => tree.FilePath.EndsWith(suffix, StringComparison.OrdinalIgnoreCase))
        || tree.GetRoot(token).GetLeadingTrivia().Any(trivia => trivia.ToString().IndexOf("<auto-generated", StringComparison.OrdinalIgnoreCase) >= 0);
}
