using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Formatting;
using Microsoft.CodeAnalysis.Text;

namespace DynaSharp.Generators;

/// <summary>
/// The edits the code fixes share, as changes of the text, so that what is around them keeps its spacing, its line ends and its comments: whether a file can be edited, an attribute removed or
/// added, a named argument set. Only the code fixes call it, so only an IDE loads it.
/// </summary>
internal static class SourceEdits
{
    private const string ExprImport = "DynaSharp.Expr";

    private static readonly string[] GeneratedSuffixes = [".g.cs", ".g.i.cs", ".designer.cs", ".generated.cs"];

    private static readonly SyntaxKind[] AccessibilityKinds = [SyntaxKind.PublicKeyword, SyntaxKind.InternalKeyword, SyntaxKind.ProtectedKeyword, SyntaxKind.PrivateKeyword, SyntaxKind.FileKeyword];

    /// <summary>Whether a tool writes the file, which loses an edit when it runs again. The same tests as the compiler's for generated code, by name and by header.</summary>
    public static bool IsGenerated(SyntaxTree tree, CancellationToken token) =>
        GeneratedSuffixes.Any(suffix => tree.FilePath.EndsWith(suffix, StringComparison.OrdinalIgnoreCase))
        || tree.GetRoot(token).GetLeadingTrivia().Any(trivia => trivia.ToString().IndexOf("<auto-generated", StringComparison.OrdinalIgnoreCase) >= 0);

    /// <summary>The document of a tree of the solution that can be edited, or null.</summary>
    public static Document? Editable(Solution solution, SyntaxTree? tree, CancellationToken token) =>
        solution.GetDocument(tree) is { } document && !IsGenerated(tree!, token) ? document : null;

    /// <summary>The document of a syntax reference that can be edited, with the node, or null.</summary>
    public static (Document Document, SyntaxNode Node)? Editable(Solution solution, SyntaxReference? reference, CancellationToken token) =>
        reference is not null && Editable(solution, reference.SyntaxTree, token) is { } document ? (document, reference.GetSyntax(token)) : null;

    /// <summary>The innermost node at a span, the one a diagnostic stands on.</summary>
    public static SyntaxNode NodeAt(SyntaxNode root, TextSpan span) => root.FindNode(span, getInnermostNodeForTie: true);

    /// <summary>The attribute a diagnostic stands on, or null where it stands elsewhere, such as on a type in place of an attribute in metadata.</summary>
    public static AttributeSyntax? AttributeAt(SyntaxNode root, TextSpan span) => NodeAt(root, span).FirstAncestorOrSelf<AttributeSyntax>();

    /// <summary>Applies changes to the documents of a solution; those of one document must not overlap.</summary>
    public static async Task<Solution> ApplyAsync(Solution solution, IEnumerable<(DocumentId Document, TextChange Change)> changes, CancellationToken token)
    {
        foreach (var group in changes.GroupBy(static change => change.Document))
        {
            var text = await solution.GetDocument(group.Key)!.GetTextAsync(token).ConfigureAwait(false);
            solution = solution.WithDocumentText(group.Key, text.WithChanges(group.Select(static change => change.Change).Distinct().OrderBy(static change => change.Span.Start)));
        }

        return solution;
    }

    /// <summary>Applies changes to one document.</summary>
    public static async Task<Document> ApplyAsync(Document document, IEnumerable<TextChange> changes, CancellationToken token)
    {
        var text = await document.GetTextAsync(token).ConfigureAwait(false);
        return document.WithText(text.WithChanges(changes.OrderBy(static change => change.Span.Start)));
    }

    /// <summary>
    /// Removes an attribute: with the comma after it, or before it for the last of a list, and the list with it when it is alone there, the whole line where the list stands alone on one.
    /// </summary>
    public static TextChange RemoveAttribute(SourceText text, AttributeSyntax attribute)
    {
        var list = (AttributeListSyntax)attribute.Parent!;
        var attributes = list.Attributes;
        if (attributes.Count == 1)
        {
            return new TextChange(WithItsSpace(text, list.Span), string.Empty);
        }

        var index = attributes.IndexOf(attribute);
        var span = index < attributes.Count - 1
            ? TextSpan.FromBounds(attribute.SpanStart, attributes[index + 1].SpanStart)
            : TextSpan.FromBounds(attributes[index - 1].Span.End, attribute.Span.End);
        return new TextChange(span, string.Empty);
    }

    /// <summary>The removal of an attribute that a syntax reference points at, in its document, or null where it cannot be edited.</summary>
    public static (DocumentId Document, TextChange Change)? RemoveAttribute(Solution solution, SyntaxReference? reference, CancellationToken token) =>
        Editable(solution, reference, token) is { } place ? (place.Document.Id, RemoveAttribute(place.Node.SyntaxTree.GetText(token), (AttributeSyntax)place.Node)) : null;

    /// <summary>The short name of an attribute as the message of a diagnostic writes it: <c>PartitionKey</c> for <c>DynaSharp.Mapping.PartitionKeyAttribute</c>.</summary>
    public static string ShortName(INamedTypeSymbol attribute) => attribute.Name.Substring(0, attribute.Name.Length - nameof(Attribute).Length);

    /// <summary>Whether modifiers name an accessibility, <c>file</c> included.</summary>
    public static bool NamesAccessibility(SyntaxTokenList modifiers) => modifiers.Any(static modifier => AccessibilityKinds.Contains(modifier.Kind()));

    /// <summary>The changes that put a keyword, such as <c>private protected</c>, in place of the accessibility that modifiers name, which they must.</summary>
    public static IEnumerable<TextChange> ReplaceAccessibility(SourceText text, SyntaxTokenList modifiers, string keyword)
    {
        var named = modifiers.Where(static modifier => AccessibilityKinds.Contains(modifier.Kind())).ToList();
        return named.Skip(1).Select(other => Remove(text, other)).Prepend(new TextChange(named[0].Span, keyword));
    }

    /// <summary>Removes a node with its space: the whole line where it stands alone on one, else the spaces after it, or before it at the end of a line.</summary>
    public static TextChange Remove(SourceText text, SyntaxNodeOrToken node) => new(WithItsSpace(text, node.Span), string.Empty);

    /// <summary>
    /// Adds an attribute list in front of a declaration, after the lists it has: on a line of its own with the indent of the declaration where the declaration starts its line, else on its line.
    /// A parameter takes it on its line.
    /// </summary>
    /// <param name="text">The text of the document.</param>
    /// <param name="declaration">The member, type or parameter.</param>
    /// <param name="list">The list to add, such as <c>[DynamoDbIgnore]</c>.</param>
    public static TextChange AddAttributeList(SourceText text, SyntaxNode declaration, string list)
    {
        var lists = declaration.ChildNodes().OfType<AttributeListSyntax>().ToList();
        var token = lists.Count > 0 ? lists[lists.Count - 1].GetLastToken().GetNextToken() : declaration.GetFirstToken();
        var position = token.SpanStart;
        var line = text.Lines.GetLineFromPosition(position);
        var indent = text.ToString(TextSpan.FromBounds(line.Start, position));
        if (declaration is ParameterSyntax || indent.Any(static character => !IsSpace(character)))
        {
            return new TextChange(new TextSpan(position, 0), list + " ");
        }

        return new TextChange(new TextSpan(position, 0), list + LineBreakBefore(text, line) + indent);
    }

    /// <summary>Whether <paramref name="call"/>, an <c>Attr(...)</c>, binds at <paramref name="position"/> as the file stands, without <c>using static DynaSharp.Expr;</c> added.</summary>
    public static bool AttrBinds(SemanticModel model, int position, ExpressionSyntax call) =>
        model.GetSpeculativeSymbolInfo(position, call, SpeculativeBindingOption.BindAsExpression).Symbol is not null;

    /// <summary>The file with <c>using static DynaSharp.Expr;</c> added, which a fix that writes <c>Attr(...)</c> needs where the name does not bind.</summary>
    public static CompilationUnitSyntax AddExprImport(CompilationUnitSyntax root)
    {
        var import = SyntaxFactory.UsingDirective(SyntaxFactory.ParseName(ExprImport))
            .WithStaticKeyword(SyntaxFactory.Token(SyntaxKind.StaticKeyword))
            .WithAdditionalAnnotations(Formatter.Annotation);
        return root.AddUsings(import);
    }

    /// <summary>Adds an attribute of DynaSharp in a list of its own in front of a declaration, by its short name where it binds there, as <see cref="AddAttributeList"/> does.</summary>
    /// <param name="model">The semantic model of the tree of the declaration.</param>
    /// <param name="declaration">The member, type or parameter.</param>
    /// <param name="metadataName">The metadata name of the attribute, such as <see cref="WellKnownNames.IgnoreAttribute"/>.</param>
    /// <param name="target">The target to write, such as <c>method</c>, or null for none.</param>
    /// <param name="token">The token to cancel.</param>
    public static TextChange AddAttribute(SemanticModel model, SyntaxNode declaration, string metadataName, string? target, CancellationToken token)
    {
        var name = AttributeName(model, declaration.SpanStart, metadataName);
        return AddAttributeList(declaration.SyntaxTree.GetText(token), declaration, "[" + (target is null ? string.Empty : target + ": ") + name + "]");
    }

    /// <summary>A property of a type or of a base type by its name, which a diagnostic of the generator named, so there is one.</summary>
    public static IPropertySymbol PropertyOf(INamedTypeSymbol type, string name)
    {
        for (var current = type; ; current = current.BaseType!)
        {
            if (current.GetMembers(name).OfType<IPropertySymbol>().FirstOrDefault() is { } property)
            {
                return property;
            }
        }
    }

    /// <summary>The name to write for an attribute of DynaSharp at a place: the short one where it binds there, else the name in full.</summary>
    /// <param name="model">The semantic model of the document.</param>
    /// <param name="position">Where the attribute goes.</param>
    /// <param name="metadataName">Its metadata name, such as <see cref="WellKnownNames.IgnoreAttribute"/>.</param>
    public static string AttributeName(SemanticModel model, int position, string metadataName)
    {
        var full = metadataName.Substring(0, metadataName.Length - nameof(Attribute).Length);
        var simple = full.Substring(full.LastIndexOf('.') + 1);
        var probe = SyntaxFactory.Attribute(SyntaxFactory.IdentifierName(simple));
        return model.GetSpeculativeSymbolInfo(position, probe).Symbol?.ContainingType.ToDisplayString() == metadataName ? simple : "global::" + full;
    }

    /// <summary>Whether an attribute binds to the attribute of DynaSharp with that metadata name.</summary>
    public static bool Is(SemanticModel model, AttributeSyntax attribute, string metadataName, CancellationToken token) =>
        model.GetSymbolInfo(attribute, token).Symbol?.ContainingType.ToDisplayString() == metadataName;

    /// <summary>An attribute with a named argument set to a value: the one it has, or one added after its other arguments.</summary>
    public static AttributeSyntax WithNamedArgument(AttributeSyntax attribute, string name, string value)
    {
        var arguments = attribute.ArgumentList ?? SyntaxFactory.ParseAttributeArgumentList("()")!;
        var existing = arguments.Arguments.FirstOrDefault(argument => argument.NameEquals?.Name.Identifier.ValueText == name);
        if (existing is not null)
        {
            return attribute.ReplaceNode(existing.Expression, SyntaxFactory.ParseExpression(value).WithTriviaFrom(existing.Expression));
        }

        var added = SyntaxFactory.ParseAttributeArgumentList("(" + name + " = " + value + ")")!.Arguments[0];
        added = arguments.Arguments.Count > 0 ? added.WithLeadingTrivia(SyntaxFactory.Space) : added;
        return attribute.WithArgumentList(arguments.AddArguments(added));
    }

    /// <summary>The change that sets a named argument of an attribute.</summary>
    public static TextChange SetNamedArgument(AttributeSyntax attribute, string name, string value) =>
        new(attribute.Span, WithNamedArgument(attribute, name, value).ToString());

    // The line break the line before has, which is the one of the file around the place; the first line takes its own.
    private static string LineBreakBefore(SourceText text, TextLine line)
    {
        var before = line.LineNumber > 0 ? text.Lines[line.LineNumber - 1] : line;
        var lineBreak = text.ToString(TextSpan.FromBounds(before.End, before.EndIncludingLineBreak));
        return lineBreak.Length > 0 ? lineBreak : "\n";
    }

    private static TextSpan WithItsSpace(SourceText text, TextSpan span)
    {
        var first = text.Lines.GetLineFromPosition(span.Start);
        var last = text.Lines.GetLineFromPosition(span.End);
        var start = span.Start;
        while (start > first.Start && IsSpace(text[start - 1]))
        {
            start--;
        }

        var end = span.End;
        while (end < last.End && IsSpace(text[end]))
        {
            end++;
        }

        if (start == first.Start && end == last.End)
        {
            return TextSpan.FromBounds(first.Start, last.EndIncludingLineBreak);
        }

        return end > span.End ? TextSpan.FromBounds(span.Start, end) : TextSpan.FromBounds(start, span.End);
    }

    private static bool IsSpace(char character) => character is ' ' or '\t';
}
