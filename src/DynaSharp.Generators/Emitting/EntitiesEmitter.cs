using System.Text;
using Microsoft.CodeAnalysis;

namespace DynaSharp.Generators;

/// <summary>
/// Writes the class <c>DynamoDbEntities</c> of an assembly, whose <c>IncludingAll()</c> is <c>Including&lt;T&gt;()</c> of every entity: a direct call per type, with nothing looked up at run time.
/// </summary>
internal static class EntitiesEmitter
{
    /// <summary>The file. A dash is in no hint name of a type, so it cannot clash with one, whatever the types are called.</summary>
    public const string HintName = "DynaSharp-DynamoDbEntities.g.cs";

    private const string Header =
        "// <auto-generated/>\n"
        + "#nullable enable\n"
        + "#pragma warning disable CS0612, CS0618\n"
        + "\n";

    public static void Emit(SourceProductionContext output, EntitiesClass? entities)
    {
        if (entities is not null)
        {
            output.AddSource(HintName, Render(entities));
        }
    }

    private static string Render(EntitiesClass entities)
    {
        var file = new StringBuilder(Header);
        var code = new IndentedCode(file, depth: 0);
        code.Line($"namespace {entities.Namespace};");
        code.Blank();
        code.Line("/// <summary>The entities of this assembly, for <see cref=\"global::DynaSharp.CreateTableCommand\"/>.</summary>");
        code.Line(CodeText.GeneratedCode);
        code.Line($"{entities.Accessibility} static class {RegistryBuilder.ClassName}");
        code.Open();
        code.Line("/// <summary>");
        code.Line("/// Includes every <c>[DynamoDbEntity]</c> of this assembly, as an <see cref=\"global::DynaSharp.CreateTableCommand.Including{TOther}\"/> of each does, so that none of their indexes is left out:");
        code.Line($"/// {string.Join(", ", entities.Entities.Select(static entity => $"<see cref=\"{entity}\"/>"))}.");
        code.Line("/// </summary>");
        code.Line("/// <param name=\"command\">The command.</param>");
        code.Line("/// <returns>The command.</returns>");
        code.Line("/// <exception cref=\"global::System.ArgumentNullException\"><paramref name=\"command\"/> is null.</exception>");
        code.Line("/// <exception cref=\"global::System.ArgumentException\">An entity disagrees with the table or with an entity before it, as <see cref=\"global::DynaSharp.CreateTableCommand.Including{TOther}\"/> says.</exception>");
        code.Line(CodeText.GeneratedCode);
        code.Line("public static global::DynaSharp.CreateTableCommand IncludingAll(this global::DynaSharp.CreateTableCommand command)");
        code.Open();
        code.Line("global::System.ArgumentNullException.ThrowIfNull(command);");
        code.Line("return command");
        code.Indent();
        for (var index = 0; index < entities.Entities.Count; index++)
        {
            code.Line($".Including<{entities.Entities[index]}>(){(index + 1 == entities.Entities.Count ? ";" : string.Empty)}");
        }

        code.Outdent();
        code.Close();
        code.Close();
        return file.ToString();
    }
}
